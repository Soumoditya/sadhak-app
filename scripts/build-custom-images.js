/**
 * Scans assets/custom/{deities,food,wallpapers} for image files the owner has
 * dropped in, and generates constants/customImages.generated.ts with static
 * require() entries (React Native needs static requires — it can't load images
 * by a dynamic path, which is why this generator exists).
 *
 * Run it after adding/removing images:   node scripts/build-custom-images.js
 * (Claude runs this for you when you say "I added images".)
 *
 * Naming: the FILE NAME (without extension), lowercased, is the "key".
 *   assets/custom/deities/shiva.jpg   -> key "shiva"
 * The registries match these keys to the right deity/dish/wallpaper.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CUSTOM = path.join(ROOT, 'assets', 'custom');
const OUT = path.join(ROOT, 'constants', 'customImages.generated.ts');
const EXT = new Set(['.jpg', '.jpeg', '.png', '.webp']);

function scan(folder) {
  const dir = path.join(CUSTOM, folder);
  if (!fs.existsSync(dir)) return {};
  const map = {};
  for (const file of fs.readdirSync(dir)) {
    const ext = path.extname(file).toLowerCase();
    if (!EXT.has(ext)) continue;               // ignore .gitkeep / README / etc.
    const key = path.basename(file, ext).toLowerCase().trim();
    // Path is relative to the constants/ folder where the output lives.
    map[key] = `../assets/custom/${folder}/${file}`;
  }
  return map;
}

function emit(name, map) {
  const entries = Object.entries(map)
    .map(([k, p]) => `  ${JSON.stringify(k)}: require(${JSON.stringify(p)}),`)
    .join('\n');
  return `export const ${name}: Record<string, number> = {\n${entries}\n};\n`;
}

const deities = scan('deities');
const food = scan('food');
const wallpapers = scan('wallpapers');

const header =
  '// AUTO-GENERATED by scripts/build-custom-images.js — do not edit by hand.\n' +
  '// Holds the owner\'s own images (dropped into assets/custom/**). Empty is fine.\n\n';

fs.writeFileSync(
  OUT,
  header + emit('CUSTOM_DEITIES', deities) + '\n' + emit('CUSTOM_FOOD', food) + '\n' + emit('CUSTOM_WALLPAPERS', wallpapers),
  'utf8',
);

const n = Object.keys(deities).length + Object.keys(food).length + Object.keys(wallpapers).length;
console.log(`customImages.generated.ts written: ${Object.keys(deities).length} deities, ${Object.keys(food).length} food, ${Object.keys(wallpapers).length} wallpapers (${n} total).`);
